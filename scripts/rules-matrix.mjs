#!/usr/bin/env node
// Generates docs/rules.md: every eslint-plugin-vue rule → oxlint native / oxlint-vue-rs status,
// upstream test results, corpus results.
//
// usage: node scripts/rules-matrix.mjs <upstream-status.json> [corpus-summary.json]
//   upstream-status.json: `UPSTREAM_STATUS=… cargo test --test upstream`
//   corpus-summary.json:  { "<rule>": { "match": n, "missing": n, "extra": n, "msgDiff": n } } (optional)
import fs from 'node:fs'
import { execFileSync } from 'node:child_process'
import { fileURLToPath } from 'node:url'

const root = fileURLToPath(new URL('..', import.meta.url))
const inv = JSON.parse(fs.readFileSync(root + 'tests/rules-inventory.json', 'utf8'))
const status = JSON.parse(fs.readFileSync(process.argv[2], 'utf8'))
const corpus = process.argv[3] ? JSON.parse(fs.readFileSync(process.argv[3], 'utf8')) : {}
const skips = JSON.parse(fs.readFileSync(root + 'tests/upstream-skips.json', 'utf8'))
const native = new Set(inv.native)
// Implementation status from the binary itself (`--rules`), so rules without upstream cases count too.
const implemented = new Set(
  execFileSync(root + 'target/release/oxlint-vue-rs', ['--rules'], { encoding: 'utf8' })
    .split('\n')
    .filter((l) => l && !l.includes('not implemented'))
    .map((l) => l.split(/\s+/)[0].split('/').slice(1).join('/')),
)

const cat = (m) => {
  const c = m.categories
  if (c.includes('vue3-essential') || c.includes('vue2-essential')) return 'essential'
  if (c.includes('vue3-strongly-recommended') || c.includes('vue2-strongly-recommended')) return 'strongly-recommended'
  if (c.includes('vue3-recommended') || c.includes('vue2-recommended')) return 'recommended'
  if (c.includes('base')) return 'base'
  return 'uncategorized'
}
const vue2only = (m) => m.categories.some((c) => c.startsWith('vue2')) && !m.categories.some((c) => c.startsWith('vue3'))

let rows = []
const counts = { native: 0, ours: 0, missing: 0, cases: 0, pass: 0, skipped: 0, fail: 0 }
for (const name of inv.all) {
  const m = inv.meta[name]
  let where, tests = '—', notes = []
  if (native.has(name)) {
    where = 'oxlint native'
    counts.native++
  } else {
    const s = status[name]
    if (implemented.has(name)) {
      where = '**oxlint-vue-rs**'
      counts.ours++
      if (s) {
        counts.cases += s.total
        counts.pass += s.pass
        counts.skipped += s.skipped
        counts.fail += s.fail
        tests = `${s.pass}/${s.total}` + (s.skipped ? ` (${s.skipped} skipped)` : '')
      } else tests = 'no upstream RuleTester cases'
      const own = Object.entries(skips).filter(([k]) => k.split('#')[0].split('/')[0] === name)
      for (const [k, why] of own) notes.push(`skip ${k.split('#')[1]}: ${why}`)
    } else {
      where = 'missing'
      counts.missing++
    }
  }
  const c = corpus[name]
  const corp = c ? `${c.match} match, ${c.missing} missing, ${c.extra} extra` : '—'
  if (m.deprecated) notes.unshift('deprecated')
  if (vue2only(m)) notes.unshift('Vue 2 only')
  rows.push(`| [${name}](https://eslint.vuejs.org/rules/${name}.html) | ${cat(m)} | ${m.fixable ? 'fix' : ''}${m.hasSuggestions ? (m.fixable ? ', ' : '') + 'suggest' : ''} | ${where} | ${tests} | ${corp} | ${notes.join('; ')} |`)
}

const out = `# Rule matrix

Generated by \`node scripts/rules-matrix.mjs\` — eslint-plugin-vue **10.12.1** (${inv.all.length} rules) vs
oxlint **1.93.0** native \`vue/*\` rules vs oxlint-vue-rs.

| | rules |
|---|---:|
| oxlint native (script-only, use \`vue/<rule>\` in oxlint) | ${counts.native} |
| **oxlint-vue-rs** (use \`vue-rs/<rule>\`) | ${counts.ours} |
| missing | ${counts.missing} |

Upstream RuleTester cases for oxlint-vue-rs rules: **${counts.pass}/${counts.cases} pass**, ${counts.skipped} skipped
(type-aware or unsupported parser options; reasons below), ${counts.fail} failing. A case passes when every diagnostic
(line, column, end line, end column, message), the fix output and every suggestion equal the real eslint-plugin-vue run.

"Corpus" = the rule at default options on 9 real projects (4121 \`.vue\` files) vs eslint-plugin-vue, matching
file + line + column + message (see [compatibility.md](compatibility.md)). Rules that need options to report anything
show 0 there.

| Rule | Category | Fix | Where | Upstream cases | Corpus | Notes |
|---|---|---|---|---|---|---|
${rows.join('\n')}
`
fs.writeFileSync(root + 'docs/rules.md', out)
console.log(counts)
